#!/usr/bin/env bash
set -euo pipefail

clickhouse-client --user "$CLICKHOUSE_USER" --password "$CLICKHOUSE_PASSWORD" --multiquery <<SQL
CREATE DATABASE IF NOT EXISTS peerdb;
CREATE DATABASE IF NOT EXISTS hms_raw;
CREATE DATABASE IF NOT EXISTS hms_core;
CREATE DATABASE IF NOT EXISTS hms_mart;
CREATE DATABASE IF NOT EXISTS hms_semantic;
CREATE DATABASE IF NOT EXISTS hms_ops;

CREATE USER IF NOT EXISTS ${PEERDB_CLICKHOUSE_USER} IDENTIFIED WITH sha256_password BY '${PEERDB_CLICKHOUSE_PASSWORD}';
GRANT INSERT, SELECT, DROP, CREATE TABLE, ALTER ADD COLUMN ON peerdb.* TO ${PEERDB_CLICKHOUSE_USER};
GRANT CREATE TEMPORARY TABLE, S3 ON *.* TO ${PEERDB_CLICKHOUSE_USER};

CREATE USER IF NOT EXISTS ${SUPERSET_CLICKHOUSE_USER} IDENTIFIED WITH sha256_password BY '${SUPERSET_CLICKHOUSE_PASSWORD}';
GRANT SELECT ON hms_semantic.* TO ${SUPERSET_CLICKHOUSE_USER};
SQL
